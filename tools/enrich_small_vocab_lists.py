def merge_bank(bank: list, incoming: list[dict]) -> tuple[int, int, dict[str, str]]:
    by_id = {w["id"]: i for i, w in enumerate(bank)}
    by_word = {(w.get("word") or "").strip().lower(): w["id"] for w in bank}
    added = updated = 0
    id_map: dict[str, str] = {}
    for raw in incoming:
        e = {k: v for k, v in raw.items() if not k.startswith("_")}
        if e["id"] in by_id:
            cur = bank[by_id[e["id"]]]
            for k, v in e.items():
                if k == "id":
                    continue
                if k in ("synonyms", "antonyms", "word_family", "tags"):
                    if v:
                        cur[k] = v
                elif v not in ("", None):
                    cur[k] = v
            bank[by_id[e["id"]]] = cur
            id_map[e["id"]] = e["id"]
            updated += 1
        elif e["word"].lower() in by_word:
            real = by_word[e["word"].lower()]
            id_map[e["id"]] = real
            i = by_id[real]
            cur = bank[i]
            for k, v in e.items():
                if k == "id":
                    continue
                if k in ("synonyms", "antonyms", "word_family", "tags"):
                    if v:
                        cur[k] = v
                elif v not in ("", None):
                    cur[k] = v
            bank[i] = cur
            updated += 1
        else:
            bank.append(e)
            by_id[e["id"]] = len(bank) - 1
            by_word[e["word"].lower()] = e["id"]
            id_map[e["id"]] = e["id"]
            added += 1
    return added, updated, id_map


def append_ids(L: dict, ids: list[str]) -> None:
    seen = set(L.get("word_ids") or [])
    out = list(L.get("word_ids") or [])
    for wid in ids:
        if wid and wid not in seen:
            out.append(wid)
            seen.add(wid)
    L["word_ids"] = out


def prune_off_theme(L: dict, lookup: dict, keep_pred) -> None:
    kept = []
    for wid in L.get("word_ids") or []:
        w = lookup.get(wid)
        if w is None or keep_pred(w):
            kept.append(wid)
    L["word_ids"] = kept


def fill(L: dict, bank: list, pred, min_n: int = MIN_SIZE) -> None:
    seen = set(L.get("word_ids") or [])
    out = list(L.get("word_ids") or [])
    for w in bank:
        if len(out) >= min_n:
            break
        if not keep_word(w):
            continue
        wid = w.get("id")
        if not wid or wid in seen:
            continue
        if pred(w):
            out.append(wid)
            seen.add(wid)
    L["word_ids"] = out


def blob(w: dict) -> str:
    return " ".join(
        [
            str(w.get("word") or ""),
            str(w.get("meaning_en") or ""),
            str(w.get("category") or ""),
            " ".join(w.get("tags") or []),
        ]
    ).lower()


def is_adj(w: dict) -> bool:
    return "adj" in str(w.get("part_of_speech") or "").lower()


def is_verb(w: dict) -> bool:
    pos = str(w.get("part_of_speech") or "").lower()
    return pos.startswith("verb") or "phrasal" in pos


def is_phrasal(w: dict) -> bool:
    pos = str(w.get("part_of_speech") or "").lower()
    tags = " ".join(w.get("tags") or []).lower()
    if "phrasal" in pos or "phrasal" in tags:
        return True
    word = str(w.get("word") or "")
    return ("verb" in pos) and (" " in word)


