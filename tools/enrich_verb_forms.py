def slug(w: str) -> str:
    return "verb:" + re.sub(r"[^a-z0-9]+", "-", w.strip().lower()).strip("-")


def reg_forms(v1: str) -> tuple[str, str, str, str]:
    w = v1.lower()
    if w in DOUBLE:
        v2 = w + w[-1] + "ed"
        v4 = w + w[-1] + "ing"
    elif w.endswith("ie"):
        v2 = w + "d"
        v4 = w[:-2] + "ying"
    elif w.endswith("e") and not w.endswith(("ee", "oe", "ye")):
        v2 = w + "d"
        v4 = w[:-1] + "ing"
    elif len(w) > 1 and w[-1] == "y" and w[-2] not in "aeiou":
        v2 = w[:-1] + "ied"
        v4 = w + "ing"
    else:
        v2 = w + "ed"
        v4 = w + "ing"
    if len(w) > 1 and w[-1] == "y" and w[-2] not in "aeiou":
        v5 = w[:-1] + "ies"
    elif w.endswith(("s", "sh", "ch", "x", "z", "o")):
        v5 = w + "es"
    else:
        v5 = w + "s"
    return v2, v2, v4, v5


def V(
    v1: str,
    phonetic: str,
    meaning_en: str,
    meaning_bn: str,
    present: str,
    present_bn: str,
    past: str,
    past_bn: str,
    *,
    cefr: str = "B1",
    category: str = "daily",
    irregular: bool = False,
    v2: str = "",
    v3: str = "",
    v4: str = "",
    v5: str = "",
    bags: str = "DR",
    tags: list[str] | None = None,
    perfect: str = "",
    perfect_bn: str = "",
    continuous: str = "",
    continuous_bn: str = "",
    gerund_ex: str = "",
    gerund_ex_bn: str = "",
    part_ex: str = "",
    part_ex_bn: str = "",
) -> dict:
    if cefr not in CEFR_OK:
        raise ValueError(f"B1+ only: {v1} ({cefr})")
    if irregular:
        if not all([v2, v3, v4, v5]):
            raise ValueError(f"irregular needs forms: {v1}")
    else:
        v2, v3, v4, v5 = reg_forms(v1)
    lists = [BAG[ch] for ch in bags if ch in BAG]
    return {
        "id": slug(v1),
        "v1": v1,
        "v2": v2,
        "v3": v3,
        "v4": v4,
        "v5": v5,
        "phonetic": phonetic,
        "meaning_en": meaning_en,
        "meaning_bn": meaning_bn,
        "cefr": cefr,
        "category": category,
        "irregular": irregular,
        "examples": {
            "present": present,
            "present_bn": present_bn,
            "past": past,
            "past_bn": past_bn,
            "perfect": perfect or f"They have {v3} this already.",
            "perfect_bn": perfect_bn or "তারা ইতিমধ্যে এটা করেছে।",
            "continuous": continuous or f"She is {v4} it now.",
            "continuous_bn": continuous_bn or "সে এখন এটা করছে।",
        },
        "gerund_use": f"Gerund ({v4}) — as subject or after enjoy/avoid/keep",
        "gerund_example": gerund_ex or f"{v4.capitalize()} regularly makes a difference.",
        "gerund_example_bn": gerund_ex_bn or "নিয়মিত করলে পার্থক্য হয়।",
        "participle_use": f"Past participle ({v3}) — perfect tenses and passive",
        "participle_example": part_ex or f"The issue has been {v3}.",
        "participle_example_bn": part_ex_bn or "বিষয়টি হয়ে গেছে।",
        "tags": tags or ["verb", "grammar"],
        "_lists": lists,
    }


