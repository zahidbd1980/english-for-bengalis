PROMOTE_IDS = {"verb:increase"}  # bank CEFR was A2; the verb is B1 in Cambridge


def merge_bank(bank: list, new_rows: list) -> tuple[int, int]:
    by_id = {v["id"]: i for i, v in enumerate(bank)}
    added = updated = 0
    for row in new_rows:
        item = {k: v for k, v in row.items() if k != "_lists"}
        if item["id"] in by_id:
            if item["id"] in PROMOTE_IDS and not keep_word(bank[by_id[item["id"]]]):
                bank[by_id[item["id"]]] = item
                updated += 1
            continue
        bank.append(item)
        by_id[item["id"]] = len(bank) - 1
        added += 1
    return added, updated


def append_ids(L: dict, ids: list[str]) -> None:
    seen = set(L.get("word_ids") or [])
    out = list(L.get("word_ids") or [])
    for wid in ids:
        if wid and wid not in seen:
            out.append(wid)
            seen.add(wid)
    L["word_ids"] = out


def prune(L: dict, lookup: dict, pred) -> None:
    L["word_ids"] = [wid for wid in (L.get("word_ids") or []) if pred(lookup.get(wid) or {})]


def fill(L: dict, bank: list, pred, min_n: int = MIN_SIZE) -> None:
    seen = set(L.get("word_ids") or [])
    out = list(L.get("word_ids") or [])
    for w in bank:
        if len(out) >= min_n:
            break
        if not keep_word(w):
            continue
        wid = w.get("id")
        if not wid or wid in seen:
            continue
        if pred(w):
            out.append(wid)
            seen.add(wid)
    L["word_ids"] = out


def blob(v: dict) -> str:
    return " ".join(
        [
            str(v.get("v1") or ""),
            str(v.get("meaning_en") or ""),
            str(v.get("category") or ""),
            " ".join(v.get("tags") or []),
        ]
    ).lower()


def main() -> None:
    bank = json.loads(VERB_DATA.read_text(encoding="utf-8"))
    meta = json.loads(VLISTS.read_text(encoding="utf-8"))
    lists = {L["id"]: L for L in meta.get("lists") or []}

    added, updated = merge_bank(bank, NEW)
    lookup = {v["id"]: v for v in bank}

    assigned: dict[str, list[str]] = {lid: [] for lid in VF_IDS}
    for row in NEW:
        for lid in row.get("_lists") or []:
            assigned.setdefault(lid, []).append(row["id"])

    for lid, ids in assigned.items():
        if lid == "verb-forms-master":
            continue
        L = lists.get(lid)
        if L:
            append_ids(L, ids)

    fill(lists["vf-daily-conversation"], bank, lambda v: (v.get("category") or "") in {"daily", "office", "travel"})
    fill(lists["vf-regular-starter"], bank, lambda v: not v.get("irregular"))
    fill(lists["vf-irregular-core"], bank, lambda v: bool(v.get("irregular")), min_n=60)
    fill(
        lists["vf-ielts-speaking"],
        bank,
        lambda v: (v.get("category") or "") in {"daily", "education"} or "speak" in blob(v),
    )
    fill(
        lists["vf-ielts-writing"],
        bank,
        lambda v: (v.get("category") or "") in {"ielts", "education"} or any(
            k in blob(v) for k in ("graph", "essay", "academic", "increase", "decline")
        ),
    )
    fill(
        lists["vf-ielts-reading"],
        bank,
        lambda v: (v.get("category") or "") == "ielts" or any(
            k in blob(v) for k in ("passage", "claim", "imply", "reveal", "research")
        ),
    )
    prune(lists["vf-regular-starter"], lookup, lambda v: not v.get("irregular"))
    prune(lists["vf-irregular-core"], lookup, lambda v: bool(v.get("irregular")))

